// Regenerate src/data/github.ts dari GitHub GraphQL.
// Jalankan: node scripts/fetch-github.mjs   (butuh `gh auth login`)
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const LOGIN = 'KhemalMS';
const query = `query { user(login: "${LOGIN}") { contributionsCollection { contributionCalendar { totalContributions weeks { contributionDays { date contributionCount } } } } } }`;

const res = execFileSync('gh', ['api', 'graphql', '-f', `query=${query}`], { encoding: 'utf8' });
const cal = JSON.parse(res).data.user.contributionsCollection.contributionCalendar;

const allWeeks = cal.weeks.map((w) => w.contributionDays.map((d) => d.contributionCount));
// Gunakan seluruh kalender penuh (52-53 minggu) tanpa memotong minggu kosong di awal.
const weeks = allWeeks;
const max = Math.max(...weeks.flat());

const file = `// Generated by scripts/fetch-github.mjs - jangan diedit manual.
export const contributions = {
  login: '${LOGIN}',
  total: ${cal.totalContributions},
  max: ${max},
  /** [minggu][hari] - 0 = Minggu. */
  weeks: ${JSON.stringify(weeks)} as number[][],
} as const;

export const contributionLevel = (n: number): 0 | 1 | 2 | 3 =>
  n === 0 ? 0 : n >= ${max} * 0.6 ? 3 : n >= ${max} * 0.25 ? 2 : 1;
`;

writeFileSync(new URL('../src/data/github.ts', import.meta.url), file);
console.log(`weeks=${weeks.length} total=${cal.totalContributions} max=${max}`);
